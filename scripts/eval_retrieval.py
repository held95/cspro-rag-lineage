"""Retrieval metrics on a small hand-labelled set (tenant alpha, all synthetic records ingested).

    python -m scripts.eval_retrieval [--embed ollama|hash] [--out docs/RETRIEVAL_EVAL.md]

Reports recall@k and MRR for answerable questions and the top-1 score distribution of unanswerable ones
(content that only exists in tenant beta, or is off-topic). Nothing is typed by hand: the markdown is generated
from what was measured. With `--embed hash` the numbers only validate the pipeline, not semantic quality.
"""
from __future__ import annotations

import argparse
import statistics
import tempfile
from datetime import date
from pathlib import Path
from types import SimpleNamespace

from app.container import build_container
from app.core.config import Settings
from tests.helpers import ingest_records, principal

ANSWERABLE = [
    ("What is the refund window?", "KB-001"),
    ("How many days do customers have to request a refund?", "KB-001"),
    ("How long does a refund take to reach the original payment method?", "KB-001"),
    ("Can I get my money back after delivery, and within how many days?", "KB-001"),
    ("How long does standard delivery take?", "KB-002"),
    ("What is the express delivery time?", "KB-002"),
    ("What happens if a delivery is later than the SLA?", "KB-002"),
    ("Do late deliveries qualify for a shipping credit?", "KB-002"),
    ("What is the first response time for a P1 incident?", "KB-003"),
    ("Who should be paged for a P1 incident?", "KB-003"),
    ("What do you do when a P1 incident starts, open a bridge call?", "KB-003"),
    ("How fast must we respond to a P1?", "KB-003"),
    ("What did the agent say in ticket 1001 about damaged parcels?", "TCK-1001"),
    ("Which customer asked about returning a damaged parcel?", "TCK-1001"),
    ("What was added in release 2026.4?", "KB-005"),
    ("Which bug was fixed in invoices in the release notes?", "KB-005"),
    ("What error did the payment gateway log on 2026-04-02?", "LOG-2001"),
    ("Why did the refund job fail for order ORD-7781?", "LOG-2002"),
    ("Is the refund job going to retry?", "LOG-2002"),
    ("What was ticket 1002 about?", "TCK-1002"),
]
UNANSWERABLE = [
    "What is the wholesale tier discount?",
    "What is the internal audit token?",
    "How long is the product warranty?",
    "Does the warranty cover water damage?",
    "Does the warranty cover a cracked screen?",
    "Who won the 1998 football world cup?",
    "What is the capital of Australia?",
    "How do I bake sourdough bread?",
    "What is the CEO's salary?",
    "How do I reset my password on the mobile app?",
]
KS = (1, 3, 5)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--embed", choices=["ollama", "hash"], default="ollama")
    ap.add_argument("--out", type=Path, default=Path("docs/RETRIEVAL_EVAL.md"))
    ap.add_argument("--threshold", type=float, default=Settings().min_score)
    a = ap.parse_args()

    tmp = Path(tempfile.mkdtemp(prefix="cspro_ret_"))
    settings = Settings(ledger_path=str(tmp / "l.db"), vector_path=None, embed_backend=a.embed, min_score=0.0)  # the LLM is never called here
    c = build_container(settings)
    ingest_records(SimpleNamespace(service=c.ingestion), "full")
    p = principal("alpha", groups=("support", "oncall"))

    ranks, top1_ans, top1_no = [], [], []
    for q, expected in ANSWERABLE:
        hits = c.retriever.retrieve(p, q, 5).hits
        docs = [h.doc_id for h in hits]
        ranks.append(docs.index(expected) + 1 if expected in docs else None)
        top1_ans.append(hits[0].score)
    for q in UNANSWERABLE:
        top1_no.append(c.retriever.retrieve(p, q, 5).hits[0].score)

    n = len(ANSWERABLE)
    recall = {k: sum(1 for r in ranks if r is not None and r <= k) / n for k in KS}
    mrr = sum(1 / r for r in ranks if r) / n
    thr = a.threshold
    accepted_no = sum(1 for s in top1_no if s >= thr)
    rejected_ans = sum(1 for s in top1_ans if s < thr)

    def dist(v):
        return f"min {min(v):.3f} / median {statistics.median(v):.3f} / max {max(v):.3f}"

    lines = [
        "# Retrieval evaluation (generated by `python -m scripts.eval_retrieval`)", "",
        f"Date: {date.today().isoformat()} · embedder: `{a.embed}` (`{c.embed_model}`) · tenant alpha, principal with groups support+oncall · "
        f"{n} answerable and {len(UNANSWERABLE)} unanswerable hand-labelled questions · `min_score` evaluated at {thr}.", "",
        "Labels were written by the author of the code (not independent); n is small; one run. "
        + ("**Hash embedder: pipeline check only, not semantic quality.**" if a.embed == "hash" else ""), "",
        "## Answerable questions", "",
        "| metric | value |", "|---|---|",
        *[f"| recall@{k} | {recall[k]:.2f} |" for k in KS], f"| MRR | {mrr:.3f} |",
        f"| top-1 score | {dist(top1_ans)} |",
        f"| rejected by `min_score` {thr} | {rejected_ans}/{n} |", "",
        "## Unanswerable questions (beta-only or off-topic)", "",
        "| metric | value |", "|---|---|",
        f"| top-1 score | {dist(top1_no)} |",
        f"| still accepted by `min_score` {thr} (the LLM must abstain) | {accepted_no}/{len(UNANSWERABLE)} |", "",
        "The score ranges of the two groups overlap whenever the unanswerable max is above the answerable min "
        f"(here {max(top1_no):.3f} vs {min(top1_ans):.3f}); the threshold then cannot separate them and the model's "
        "abstention covers the rest.", "",
    ]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
