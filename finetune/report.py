"""Build ``finetune/results/baseline_vs_adapted.md`` from the per-arm JSON result files.

    python -m finetune.report

Reads ``finetune/results/{arm}__{set}.json`` (written by ``finetune.eval``) and
``finetune/outputs/run_meta.json`` (written by ``finetune.train``). Never invents numbers:
a missing or NOT EXECUTED arm is printed as ``NOT EXECUTED``.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).parent
ARMS = (("base", "Base zero-shot"), ("fewshot", "Base few-shot"), ("adapted", "Adapted (QLoRA)"))
REQUIRED_ARMS = ("base", "adapted")  # few-shot is optional and only shown if it was run
SETS = (("heldout", "Templated held-out (unseen scenario families)"),
        ("ood", "Hand-written OOD set"))
METRICS = (
    ("schema_valid_rate", "Schema-valid rate (unconstrained HF generation)", "higher"),
    ("citation_id_valid_rate", "Citation id valid", "higher"),
    ("citation_quote_valid_rate", "Citation quote verbatim", "higher"),
    ("abstain_precision", "Abstention precision", "higher"),
    ("abstain_recall", "Abstention recall", "higher"),
    ("abstain_f1", "Abstention F1", "higher"),
    ("over_abstention_rate", "Over-abstention on answerable", "lower"),
    ("conflict_precision", "Conflict precision", "higher"),
    ("conflict_recall", "Conflict recall", "higher"),
    ("conflict_f1", "Conflict F1", "higher"),
    ("injection_compliance_rate", "Injection compliance (canary leaked)", "lower"),
    ("answer_token_f1", "Answer token-F1 (answerable items)", "higher"),
)
META_KEYS = ("model", "revision", "git_sha", "gpu", "seed", "global_steps", "wall_time_s",
             "seconds_per_step", "peak_vram_gb", "final_train_loss", "started_utc", "versions")


def _load(path: Path) -> dict | None:
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    return data if data.get("status") == "EXECUTED" else None


def _cell(result: dict | None, key: str) -> str:
    if result is None:
        return "NOT EXECUTED"
    value, ci = result["metrics"].get(key), result["ci95"].get(key)
    if value is None:
        return "n/a"
    return f"{value:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else f"{value:.3f}"


def _section(results_dir: Path, set_key: str, set_title: str) -> list[str]:
    arms = [(k, label) for k, label in ARMS
            if k in REQUIRED_ARMS or (results_dir / f"{k}__{set_key}.json").exists()]
    results = {k: _load(results_dir / f"{k}__{set_key}.json") for k, _ in arms}
    ns = sorted({r["n"] for r in results.values() if r})
    lines = [f"## {set_title}", ""]
    lines.append(f"n = {', '.join(map(str, ns))} items per executed arm." if ns
                 else "No arm was executed on this set.")
    lines += ["", "| Metric | better | " + " | ".join(label for _, label in arms) + " |",
              "|---|---|" + "---|" * len(arms)]
    for key, label, better in METRICS:
        lines.append(f"| {label} | {better} | " + " | ".join(_cell(results[k], key) for k, _ in arms) + " |")
    return lines + [""]


def _meta_lines(meta_path: Path) -> list[str]:
    if not meta_path.exists():
        return ["- run metadata: not available (training NOT EXECUTED or run_meta.json missing)"]
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    return [f"- {k}: {meta[k]}" for k in META_KEYS if k in meta]


def build_report(results_dir: Path, meta_path: Path) -> str:
    lines = [
        "# Fine-tune evaluation: base vs QLoRA-adapted",
        "",
        "Generated by `python -m finetune.report` from `finetune/results/*.json`; no number is "
        "typed by hand. Cells show `value [95% bootstrap CI]`; `NOT EXECUTED` means the arm was "
        "not run and no number exists; `n/a` means the metric has no denominator (e.g. no citations).",
        "",
        "Caveats: small n (60 templated + 15 hand-written items) gives wide CIs; the data are "
        "synthetic; both arms use the same 4-bit base model, prompt and greedy decoding. "
        "Schema validity is for unconstrained HF generation; the app constrains output with a "
        "JSON schema, so that row does not transfer to the served path.",
        "",
        "## Training run metadata",
        "",
        *_meta_lines(meta_path),
        "",
    ]
    for set_key, title in SETS:
        lines += _section(results_dir, set_key, title)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results-dir", type=Path, default=HERE / "results")
    parser.add_argument("--run-meta", type=Path, default=HERE / "outputs" / "run_meta.json")
    parser.add_argument("--out", type=Path, default=HERE / "results" / "baseline_vs_adapted.md")
    args = parser.parse_args(argv)
    md = build_report(args.results_dir, args.run_meta)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md + "\n", encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
